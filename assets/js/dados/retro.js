const capitalizeRetro = (value) => value
  .replace(/(^|\s)(\S)/g, (match, space, letter) => space + letter.toUpperCase())
  .replace(/\s(De|Da|Do|Dos|Das|La)(?=\s)/g, (match) => match.toLowerCase());

const retroNome = (texto) => retroNomes[normalizarTexto(texto).trim()] || capitalizeRetro(texto.trim().toLowerCase());

const retroGrupoNome = (grupo) => retroGrupos[normalizarTexto(grupo)] || capitalizeRetro(grupo);

// Temporada no nome do arquivo: "02-03", "2002-03", "99-2000", "1988" ou "96"
const retroTemporadaRegex = /(?<!\d)(\d{2}|\d{4})(?:-(\d{2}|\d{4}))?(?!\d)/;

// "05-06" → "2005/06", "80-81" → "1980/81", "99-2000" → "1999/2000", "96" → "1996"
const formatRetroSeason = (inicio, fim) => {
  const anoCompleto = (ano) => (ano.length === 4 ? ano : `${Number(ano) > 30 ? "19" : "20"}${ano}`);
  return fim ? `${anoCompleto(inicio)}/${fim}` : anoCompleto(inicio);
};

// Nas pastas "outros"/"outros clubes" (ou foto solta na pasta do grupo) o time vem do nome do arquivo
const retroTime = (grupo, clube, arquivo) => {
  if (clube && !normalizarTexto(clube).startsWith("outros")) {
    return retroNome(clube);
  }

  const baseName = arquivo.replace(/\.[^/.]+$/, "");
  const m = baseName.match(retroTemporadaRegex);
  return retroNome(m ? baseName.slice(0, m.index) : baseName);
};

const formatRetroName = (grupo, clube, arquivo) => {
  const baseName = arquivo.replace(/\.[^/.]+$/, "");
  const m = baseName.match(retroTemporadaRegex);
  const temporada = m ? formatRetroSeason(m[1], m[2]) : "";
  const detalhes = (m ? baseName.slice(m.index + m[0].length) : "")
    .toLowerCase()
    .replace(/\bretro\b/g, "")
    .replace(/\bspecial\b/g, "Especial")
    .replace(/\bcentenario\b/g, "Centenário");

  return `${retroTime(grupo, clube, arquivo)} Retrô ${temporada} ${capitalizeRetro(detalhes)}`
    .replace(/\s+/g, " ")
    .trim();
};

