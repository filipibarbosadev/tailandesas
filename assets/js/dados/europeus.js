const displayEuropeuName = (fileName) => {
  // Alguns arquivos vieram com a extensão sem ponto (ex.: "away-jpg")
  const baseName = fileName.replace(/\.[^/.]+$/, "").replace(/-(jpe?g|png|webp)$/i, "");
  return baseName
    .replace(/\b(?:20)?26-27\b/g, "2026/27")
    .replace(/\b(home|away|third|treino|goleiro|special|aniversary|oktoberfest|pre jogo|pré jogo|aniversario)\b/gi, (match) => {
      const labels = {
        home: "Home",
        away: "Away",
        third: "Third",
        treino: "Treino",
        goleiro: "Goleiro",
        special: "Especial",
        aniversary: "Aniversário",
        aniversario: "Aniversário",
        oktoberfest: "Oktoberfest",
        "pre jogo": "Pré-jogo",
        "pré jogo": "Pré-jogo"
      };
      return labels[normalizarTexto(match)] || match;
    })
    .replace(/\s+/g, " ")
    .trim()
    // Maiúscula no início de cada palavra (também depois de acentos), "de/da/do" minúsculos e siglas em caixa alta
    .replace(/(^|\s)(\S)/g, (match, space, letter) => space + letter.toUpperCase())
    .replace(/\s(De|Da|Do|Dos|Das)(?=\s)/g, (match) => match.toLowerCase())
    .replace(/\b(Psg|Psv|Fc)\b/g, (match) => match.toUpperCase());
};

