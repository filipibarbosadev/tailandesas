const normalizeEuropeu = (value) => value
  .normalize("NFD")
  .replace(/[\u0300-\u036f]/g, "")
  .toLowerCase();

const displayEuropeuName = (fileName) => {
  const baseName = fileName.replace(/\.[^/.]+$/, "");
  return baseName
    .replace(/\b26-27\b/g, "2026/27")
    .replace(/\b(home|away|third|treino|goleiro|special|aniversary|oktoberfest|pre jogo|pré jogo|aniversario)\b/gi, (match) => {
      const labels = {
        home: "Home",
        away: "Away",
        third: "Third",
        treino: "Treino",
        goleiro: "Goleiro",
        special: "Especial",
        aniversary: "Aniversário",
        aniversario: "Aniversário",
        oktoberfest: "Oktoberfest",
        "pre jogo": "Pré-jogo",
        "pré jogo": "Pré-jogo"
      };
      return labels[normalizeEuropeu(match)] || match;
    })
    .replace(/\s+/g, " ")
    .trim()
    .replace(/\b\w/g, (letter) => letter.toUpperCase());
};

const createEuropeuCard = ([filter, championship, fileName]) => {
  const imagePath = `../assets/camisas/europeus/${europeusFolders[filter]}/${fileName}`;
  const title = displayEuropeuName(fileName);
  const encodedPath = encodeURI(imagePath);

  return `
    <article class="catalog-card">
      <a class="catalog-card-media" href="${encodedPath}" target="_blank" rel="noopener noreferrer">
        <img src="${encodedPath}" alt="${title}" loading="lazy">
      </a>
      <div class="catalog-card-content">
        <span class="catalog-card-league">${europeusLabels[filter]}</span>
        <h2>${title}</h2>
        <p>Camisa Tailandesa 1.1.</p>
        <strong>R$ 119,90</strong>
      </div>
    </article>
  `;
};

const catalogPageSize = 24;
let catalogPage = 1;

const renderEuropeus = () => {
  const search = document.querySelector("#catalog-search");
  const filter = document.querySelector("#championship-filter");
  const grid = document.querySelector("#catalog-grid");
  const count = document.querySelector("#catalog-count");
  const empty = document.querySelector("#catalog-empty");
  const pagination = document.querySelector("#catalog-pagination");
  const previous = document.querySelector("#catalog-previous");
  const next = document.querySelector("#catalog-next");
  const pageStatus = document.querySelector("#catalog-page-status");
  const query = normalizeEuropeu(search.value.trim());

  const results = europeusCatalog.filter(([filterKey, championship, fileName]) => {
    const matchesFilter = filter.value === "all" || filter.value === filterKey;
    const searchable = normalizeEuropeu(`${fileName} ${championship} ${europeusLabels[filterKey]}`);
    return matchesFilter && (!query || searchable.includes(query));
  });

  const totalPages = Math.max(1, Math.ceil(results.length / catalogPageSize));
  catalogPage = Math.min(catalogPage, totalPages);
  const start = (catalogPage - 1) * catalogPageSize;
  const visibleResults = results.slice(start, start + catalogPageSize);

  grid.innerHTML = visibleResults.map(createEuropeuCard).join("");
  count.textContent = `${results.length} ${results.length === 1 ? "camisa encontrada" : "camisas encontradas"}`;
  empty.hidden = results.length > 0;
  pagination.hidden = results.length === 0;
  pageStatus.textContent = `Página ${catalogPage} de ${totalPages}`;
  previous.disabled = catalogPage === 1;
  next.disabled = catalogPage === totalPages;
};

document.addEventListener("DOMContentLoaded", () => {
  const search = document.querySelector("#catalog-search");
  const filter = document.querySelector("#championship-filter");
  const previous = document.querySelector("#catalog-previous");
  const next = document.querySelector("#catalog-next");
  const filterOptions = Object.entries(europeusLabels)
    .map(([value, label]) => `<option value="${value}">${label}</option>`)
    .join("");

  filter.insertAdjacentHTML("beforeend", filterOptions);
  search.addEventListener("input", () => {
    catalogPage = 1;
    renderEuropeus();
  });
  filter.addEventListener("change", () => {
    catalogPage = 1;
    renderEuropeus();
  });
  previous.addEventListener("click", () => {
    catalogPage -= 1;
    renderEuropeus();
    window.scrollTo({ top: 0, behavior: "smooth" });
  });
  next.addEventListener("click", () => {
    catalogPage += 1;
    renderEuropeus();
    window.scrollTo({ top: 0, behavior: "smooth" });
  });
  renderEuropeus();
});
